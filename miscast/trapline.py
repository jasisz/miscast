    WT = f"{ENG}/wasmtime-v46/wasmtime"; WE = f"{ENG}/wasmedge/bin/wasmedge"
    MCR = f"{REPO}/runner/target/release/mc-runner"
    NODE = os.path.expanduser("~/.nvm/versions/node/v26.3.0/bin/node"); V8 = f"{REPO}/miscast/oracle/v8.js"

    import re

    def res(p):
        out = ((p.stdout or "") + (p.stderr or "")).lower()
        # a trap shows as a non-zero exit OR any engine's trap wording (wasmtime "trap", WasmEdge "execution
        # failed: integer overflow / out of bounds", V8 "RuntimeError", a cast failure, a null dereference).
        if p.returncode != 0 or any(k in out for k in (
                "trap", "unreachable", "out of bounds", "overflow", "invalid conversion", "cast",
                "execution failed", "null", "divide", "runtimeerror")):
            return "TRAP"
        m = re.findall(r"-?\d+", p.stdout or "")
        return f"OK {m[-1]}" if m else "OK _"

    def run(eng, wasm):
        if eng == "wt": c = [WT, "run", "-W", "function-references=y,gc=y", "--invoke", "f", wasm]
        elif eng == "we": c = [WE, "run", wasm, "f"]
        elif eng == "mcr": c = [MCR, wasm, "--invoke", "f"]
        elif eng == "v8": c = [NODE, V8, wasm, "f"]
        return res(subprocess.run(c, capture_output=True, text=True))

    print("=== trapline: conformant engines must trap exactly where the spec says (or hit the baked constant) ===")
    bad = 0
    for s in range(28):
        label, export, expected, wat = trapline_gen(s)
        open("/tmp/tl.wat", "w").write(wat)
        a = subprocess.run(["wasm-tools", "parse", "/tmp/tl.wat", "-o", "/tmp/tl.wasm"], capture_output=True, text=True)
        if a.returncode != 0:
            print(f"  ASMFAIL {label}: {a.stderr.strip().splitlines()[-1][:64]}"); bad += 1; continue
        row = {e: run(e, "/tmp/tl.wasm") for e in ("wt", "we", "mcr", "v8")}
        ok = all(v == expected for v in row.values())
        bad += not ok
        print(f"  {'OK ' if ok else 'FAIL'} {label:28} exp={expected:12} {row}")
    print(f"\n28 programs, {bad} disagreeing")
